/** Labels where content came from, so demo output is never mistaken for AI output. */
export function GenerationBadge({ provider, isDemo, className }: { provider: string; isDemo: boolean; className?: string }) {
  if (provider === 'manual') return <Badge variant="secondary" className={className}><Hand /> Written manually</Badge>;
  if (provider === 'sample') return <Badge variant="warning" className={className}><FlaskConical /> Sample content</Badge>;
  if (provider === 'rule-based') return <Badge variant="warning" className={className}><FlaskConical /> Rule-based split (no AI)</Badge>;
  if (provider === 'upload') return <Badge variant="secondary" className={className}>Uploaded</Badge>;
  if (isDemo || provider === 'template-demo' || provider === 'placeholder') {
    return (
      <Badge variant="warning" className={className} title="Not generated by an AI model">
        <FlaskConical /> {provider === 'placeholder' ? 'Placeholder (no AI)' : 'Demo template (no AI)'}
      </Badge>
    );
  }
  return <Badge variant="success" className={className}><Sparkles /> AI · {provider}</Badge>;
}

export function ProviderStateBadge({ state }: { state: ProviderStatus['state'] }) {
  const map: Record<ProviderStatus['state'], { v: 'success' | 'warning' | 'danger' | 'outline' | 'info'; label: string; icon: ReactNode }> = {
    ready: { v: 'success', label: 'Ready', icon: <CheckCircle2 /> },
    demo: { v: 'warning', label: 'Demo', icon: <FlaskConical /> },
    not_configured: { v: 'outline', label: 'Not configured', icon: <CircleSlash /> },
    not_installed: { v: 'outline', label: 'Not installed', icon: <CircleSlash /> },
    unreachable: { v: 'danger', label: 'Unreachable', icon: <AlertTriangle /> },
    error: { v: 'danger', label: 'Error', icon: <XCircle /> },
  };
  const m = map[state];
  return <Badge variant={m.v}>{m.icon} {m.label}</Badge>;
}

export function SetupInstructions({ steps, className }: { steps: string[]; className?: string }) {
  if (!steps.length) return null;
  return (
    <div className={cn('rounded-md border bg-black/30 p-3', className)}>
      <p className="mb-2 flex items-center gap-1.5 text-xs font-medium text-muted-foreground"><Terminal className="h-3.5 w-3.5" /> Setup</p>
      <ol className="space-y-1 font-mono text-[11.5px] leading-relaxed text-slate-300">
        {steps.map((s, i) => (
          <li key={i} className="whitespace-pre-wrap break-words">{s}</li>
        ))}
      </ol>
    </div>
  );
}

export function UnavailableNotice({ title, message, steps, className }: { title: string; message?: string; steps?: string[]; className?: string }) {
  const [show, setShow] = useState(false);
  return (
    <div className={cn('rounded-lg border border-amber-500/30 bg-amber-500/5 p-4', className)}>
      <div className="flex items-start gap-3">
        <Cpu className="mt-0.5 h-4 w-4 shrink-0 text-amber-400" />
        <div className="min-w-0 flex-1">
          <p className="text-sm font-medium text-amber-200">{title}</p>
          {message && <p className="mt-0.5 text-sm text-muted-foreground">{message}</p>}
          {steps && steps.length > 0 && (
            <>
              <button className="mt-2 text-xs text-amber-300 underline-offset-2 hover:underline" onClick={() => setShow((s) => !s)}>
                {show ? 'Hide' : 'Show'} setup instructions
              </button>
              {show && <SetupInstructions steps={steps} className="mt-2" />}
            </>
          )}
        </div>
      </div>
    </div>
  );
}

export function JobProgress({ job, className, onRetry }: { job: Job | undefined; className?: string; onRetry?: () => void }) {
  if (!job) return null;
  const steps = (job.result as { setupInstructions?: string[] } | null)?.setupInstructions ?? [];
  if (job.status === 'failed') {
    return (
      <div className={cn('rounded-lg border border-red-500/30 bg-red-500/5 p-3', className)}>
        <div className="flex items-start justify-between gap-3">
          <div className="flex min-w-0 items-start gap-2">
            <XCircle className="mt-0.5 h-4 w-4 shrink-0 text-red-400" />
            <div className="min-w-0">
              <p className="text-sm font-medium text-red-200">{job.message === 'Provider unavailable' ? 'Engine not available — nothing was generated' : 'Generation failed'}</p>
              <p className="mt-0.5 break-words text-xs text-muted-foreground">{job.error}</p>
            </div>
          </div>
          <Button size="sm" variant="secondary" onClick={async () => {
            try { await api.post(`/jobs/${job.id}/retry`); onRetry?.(); } catch (e) { toastError(e); }
          }}>
            <RefreshCw /> Retry
          </Button>
        </div>
        {steps.length > 0 && <SetupInstructions steps={steps} className="mt-3" />}
      </div>
    );
  }
  if (job.status === 'completed') return null;
  return (
    <div className={cn('rounded-lg border bg-muted/30 p-3', className)}>
      <div className="mb-2 flex items-center justify-between gap-2 text-xs">
        <span className="flex items-center gap-2 text-muted-foreground"><Loader2 className="h-3.5 w-3.5 animate-spin text-violet-400" /> {job.message}</span>
        <span className="tabular-nums text-muted-foreground">{Math.round(job.progress * 100)}%</span>
      </div>
      <Progress value={Math.max(4, job.progress * 100)} />
    </div>
  );
}

export function ConfirmDialog({
  open, onOpenChange, title, description, confirmLabel = 'Delete', onConfirm, loading,
}: { open: boolean; onOpenChange: (o: boolean) => void; title: string; description?: string; confirmLabel?: string; onConfirm: () => void; loading?: boolean }) {
  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent>
        <DialogHeader>
          <DialogTitle>{title}</DialogTitle>
          {description && <DialogDescription>{description}</DialogDescription>}
        </DialogHeader>
        <DialogFooter>
          <Button variant="secondary" onClick={() => onOpenChange(false)}>Cancel</Button>
          <Button variant="destructive" loading={loading} onClick={onConfirm}>{confirmLabel}</Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}

export function InfluencerAvatar({ influencer, size = 40, className }: { influencer?: Pick<InfluencerView, 'name' | 'profileImageUrl' | 'characterType'> | null; size?: number; className?: string }) {
  const initials = influencer?.name.slice(0, 2).toUpperCase() ?? '?';
  return (
    <div
      className={cn('relative shrink-0 overflow-hidden rounded-full border border-white/10 bg-gradient-to-br from-violet-600 to-blue-600', className)}
      style={{ width: size, height: size }}
    >
      {influencer?.profileImageUrl ? (
        <img src={influencer.profileImageUrl} alt={influencer.name} className="h-full w-full object-cover" />
      ) : (
        <span className="flex h-full w-full items-center justify-center text-xs font-semibold text-white">{initials}</span>
      )}
    </div>
  );
}

